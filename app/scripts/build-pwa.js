// Builds the installable web version (PWA) of the app and publishes it inside the website at web/pwa, so it is served at
//   <site>/pwa/        (for example http://localhost/langoculturalinstitution/pwa/)
// next to the API it talks to (<site>/api/v1). The site's own address is read from web/config/config.php ("base"), so the same
// command works on XAMPP and on a live server. Usage:  npm run pwa   (optionally:  npm run pwa -- --base=/some/folder)
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const APP = path.join(__dirname, '..');
const WEB = path.join(APP, '..', 'web');
const OUT = path.join(APP, 'dist-web');
const TARGET = path.join(WEB, 'pwa');

function siteBase() {
  const arg = process.argv.find((a) => a.startsWith('--base='));
  if (arg) return arg.slice(7).replace(/\/+$/, '');
  try {
    const cfg = fs.readFileSync(path.join(WEB, 'config', 'config.php'), 'utf8');
    const m = cfg.match(/'base'\s*=>\s*'([^']*)'/);
    return m ? m[1].replace(/\/+$/, '') : '';
  } catch {
    return '';
  }
}

const base = `${siteBase()}/pwa`;
console.log(`Exporting the web app for ${base || '/'} …`);
fs.rmSync(OUT, { recursive: true, force: true });
// Expo's CLI is run with Node directly, which behaves the same on Windows, macOS and Linux (no shell involved).
const run = spawnSync(process.execPath, [require.resolve('expo/bin/cli', { paths: [APP] }), 'export', '--platform', 'web', '--output-dir', 'dist-web'], {
  cwd: APP,
  stdio: 'inherit',
  env: { ...process.env, EXPO_BASE_URL: base, EXPO_PUBLIC_APP_ENV: process.env.EXPO_PUBLIC_APP_ENV || 'production', NODE_ENV: 'production' },
});
if (run.status !== 0) process.exit(run.status ?? 1);

// The single-page export uses Expo's default HTML shell, so add what makes it an installable app: the web manifest, the iPhone
// icon and the service worker (offline use), all addressed from this site's own folder.
const indexFile = path.join(OUT, 'index.html');
const head = `<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Lango">
<meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no, viewport-fit=cover">
<link rel="manifest" href="${base}/manifest.webmanifest">
<link rel="apple-touch-icon" href="${base}/icon-192.png">
<script>if ('serviceWorker' in navigator) { window.addEventListener('load', function () { navigator.serviceWorker.register('${base}/sw.js').catch(function () {}); }); }</script>
<style>body{background:#F7F5EE}</style>
`;
fs.writeFileSync(indexFile, fs.readFileSync(indexFile, 'utf8').replace('</head>', head + '</head>'));

fs.rmSync(TARGET, { recursive: true, force: true });
fs.cpSync(OUT, TARGET, { recursive: true });
fs.writeFileSync(
  path.join(TARGET, '.htaccess'),
  `# Generated by app/scripts/build-pwa.js — the Lango App as a web app (single-page: unknown paths open index.html).
Options -Indexes
DirectoryIndex index.html
AddType application/manifest+json .webmanifest
<IfModule mod_rewrite.c>
RewriteEngine On
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^ index.html [L]
</IfModule>
<IfModule mod_headers.c>
<FilesMatch "(sw\\.js|manifest\\.webmanifest|index\\.html)$">
Header set Cache-Control "no-cache"
</FilesMatch>
</IfModule>
`,
);
console.log(`Published to ${path.relative(path.join(APP, '..'), TARGET)} — open ${base}/ on the site.`);
